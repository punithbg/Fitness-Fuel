export const starterFoods: Food[] = rows.map(
  ([key, name, category, preparation, calories, protein, carbs, fat, fiber, sugar]) => {
    const boneIn = name.includes('bone-in')
    const egg = category === 'Egg'
    return foodSchema.parse({
      id: `starter-food-v1-${key}`,
      ownerId: 'starter',
      updatedAt: '2026-11-05T00:00:00.000Z',
      name,
      category,
      preparation,
      unit: 'g',
      basis: 100,
      servingName: egg
        ? key === 'egg-white'
          ? 'large egg white'
          : key === 'egg-yolk'
            ? 'large egg yolk'
            : '50 g portion'
        : '100 g edible portion',
      servingSize: egg ? (key === 'egg-white' ? 33 : key === 'egg-yolk' ? 17 : 50) : 100,
      nutrients: { calories, protein, carbs, fat, fiber, sugar },
      favorite: false,
      archived: false,
      source:
        'Approximate generic reference values. Reference resource: USDA FoodData Central (https://fdc.nal.usda.gov/). Not a certified or laboratory-verified dataset.',
      notes: [
        'Per 100 g edible portion in the stated preparation. Weigh raw and cooked portions separately; no automatic cooking-yield conversion.',
        boneIn
          ? 'Exclude bones from the logged weight; these values describe edible meat/flesh, not total bone-in weight.'
          : 'Exclude inedible peel, pits, shells and bones where applicable.',
        ['Fried', 'Scrambled', 'Omelet'].includes(preparation)
          ? 'Generic recipe estimate includes cooking fat; actual oil, milk and fillings vary. Adjust to your recipe.'
          : 'No added oil, sauce or breading. Log additions separately.',
        category === 'Mutton'
          ? 'Goat and sheep are distinct entries. Cut, trimming and animal age change fat and energy substantially.'
          : '',
      ]
        .filter(Boolean)
        .join(' '),
    })
  },
)
